// Справка по сложным структурам окна тестирования схемы (issue #306). Рядом с
// полями «История ходов (JSON)», «История переписки (JSON)» и «Inputs JSON»
// показывается пиктограмма (?), по клику открывается модалка с описанием и
// примерами заполнения, включая мокание ответов отдельных LLM-узлов.

/** Пример заполнения структуры: подпись и готовый JSON, который можно скопировать. */
export interface SchemaHelpExample {
  caption: string;
  json: string;
}

/** Один раздел справки по структуре ввода теста схемы. */
export interface SchemaHelpTopic {
  id: string;
  title: string;
  /** Абзацы описания структуры. */
  description: string[];
  /** Примеры заполнения. */
  examples: SchemaHelpExample[];
  /** Дополнительные заметки-подсказки (маркированный список). */
  notes?: string[];
}

function pretty(value: unknown): string {
  return JSON.stringify(value, null, 2);
}

