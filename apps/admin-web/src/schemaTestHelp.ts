const INPUTS_TOPIC: SchemaHelpTopic = {
  id: 'inputs',
  title: 'Inputs JSON',
  description: [
    'Расширенный режим: полный объект входных данных теста, который движок ' +
      'передаёт схеме напрямую. Заменяет простые поля и даёт доступ ко всем ' +
      'параметрам, включая мокание ответов LLM.',
    'Состав полей зависит от типа схемы: action использует action и history, ' +
      'hint — history, illustration — narrative, support — user_query и ' +
      'supportHistory. Дополнительно доступны expertiseTopK и memoryTopK ' +
      '(сколько ячеек экспертизы и памяти подмешивать), а также mockResponses и ' +
      'mockUsage для подмены ответов LLM.',
    'Мокание отдельных узлов: mockResponses — это список ответов, который ' +
      'выдаётся LLM-узлам по очереди в порядке их исполнения. Первый запрос к LLM ' +
      'получает первый элемент, второй — второй и так далее. Если узлов больше, чем ' +
      'элементов, последний ответ повторяется для всех оставшихся. Так можно ' +
      'протестировать схему без реального вызова модели и точечно задать ответ ' +
      'нужному узлу, поставив его на соответствующую позицию.',
  ],
  examples: [
    {
      caption: 'action: ход игрока с моком ответа рассказчика',
      json: pretty({
        action: 'Осмотреться',
        history: [{ turn: 1, action: 'Войти в пещеру', outcome: 'Внутри прохладно и темно.' }],
        mockResponses: [{ narrative: 'Ты замечаешь сундук в углу.' }],
      }),
    },
    {
      caption: 'hint: мок подсказок для первого LLM-узла',
      json: pretty({
        history: [],
        mockResponses: [{ hints: ['Осмотреться', 'Проверить инвентарь'] }],
      }),
    },
    {
      caption: 'support: мок ответа поддержки',
      json: pretty({
        user_query: 'Не получается начать игру',
        supportHistory: [],
        expertiseTopK: 3,
        mockResponses: [{ reply: 'Проверю проблему.', summary: 'Пользователь не может начать игру' }],
      }),
    },
  ],
  notes: [
    'Элемент mockResponses может быть объектом (его сериализуют в JSON) или строкой.',
    'Пустой mockResponses (или его отсутствие) означает реальный вызов LLM-провайдера.',
    'mockUsage позволяет задать токены/стоимость мок-ответа для проверки расчёта затрат.',
  ],
};

/** Все разделы справки по ключу темы. */
export const SCHEMA_TEST_HELP: Record<string, SchemaHelpTopic> = {
  [HISTORY_TOPIC.id]: HISTORY_TOPIC,
  [SUPPORT_HISTORY_TOPIC.id]: SUPPORT_HISTORY_TOPIC,
  [INPUTS_TOPIC.id]: INPUTS_TOPIC,
};

/**
 * Возвращает раздел справки для типизированного поля теста по его ключу
 * (issue #306). Для полей без справки возвращает undefined.
 */
export function helpTopicForField(fieldKey: string): SchemaHelpTopic | undefined {
  return SCHEMA_TEST_HELP[fieldKey];
}
